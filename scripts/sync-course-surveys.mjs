#!/usr/bin/env node
/**
 * Sync Pre/Post course SurveyMonkey surveys into src/config/courseSurveys.ts
 *
 * Usage:
 *   1. Put SURVEYMONKEY_ACCESS_TOKEN in local .env (gitignored)
 *   2. npm run sync:course-surveys
 *
 * Never commits the token. Regenerates the COURSE_SURVEY_LINKS catalog from the API.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const OUT_FILE = resolve(ROOT, 'src/config/courseSurveys.ts')
const SM_API = 'https://api.surveymonkey.com/v3'

function loadEnvToken() {
  for (const name of ['.env', '.env.local']) {
    const path = resolve(ROOT, name)
    if (!existsSync(path)) continue
    const raw = readFileSync(path, 'utf8')
    for (const line of raw.split('\n')) {
      const t = line.trim()
      if (!t || t.startsWith('#')) continue
      const i = t.indexOf('=')
      if (i < 0) continue
      const key = t.slice(0, i).trim()
      if (key !== 'SURVEYMONKEY_ACCESS_TOKEN') continue
      let value = t.slice(i + 1).trim()
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1)
      }
      if (value && !value.includes('your_surveymonkey')) return value
    }
  }
  return null
}

async function smFetch(token, path) {
  const res = await fetch(`${SM_API}${path}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/json',
    },
  })
  const text = await res.text()
  if (!res.ok) {
    throw new Error(`SurveyMonkey ${path} → HTTP ${res.status}: ${text.slice(0, 400)}`)
  }
  return JSON.parse(text)
}

function inferKind(title) {
  const t = (title || '').toLowerCase()
  if (
    t.includes('pre-course') ||
    t.includes('pre course') ||
    (/\bpre\b/.test(t) && t.includes('assessment'))
  ) {
    return 'pre'
  }
  if (
    t.includes('post-course') ||
    t.includes('post course') ||
    (/\bpost\b/.test(t) && t.includes('assessment'))
  ) {
    return 'post'
  }
  return 'other'
}

/**
 * Derive fuzzy course matchers from a SurveyMonkey title.
 * Strips pre/post/assessment noise so "Digital Presence as a Transformation Leader - Pre-Course..."
 * → matchers like "digital presence".
 */
function deriveCourseMatchers(title) {
  let cleaned = title
    .replace(/pre[-\s]?course\s+assessment/gi, '')
    .replace(/post[-\s]?course\s+assessment/gi, '')
    .replace(/\bpre[-\s]?assessment\b/gi, '')
    .replace(/\bpost[-\s]?assessment\b/gi, '')
    .replace(/\bassessment\b/gi, '')
    .replace(/\byour\b/gi, '')
    .replace(/\bas a transformation leader\b/gi, '')
    .replace(/\bfor transformation leaders?\b/gi, '')
    .replace(/[-–—|:]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  const lower = cleaned.toLowerCase()
  const matchers = new Set()

  if (lower) matchers.add(lower)

  // Prefer a shorter distinctive phrase (first 2–4 words) when the title is long.
  const words = lower.split(' ').filter(Boolean)
  if (words.length >= 2) {
    matchers.add(words.slice(0, 2).join(' '))
  }
  if (words.length >= 3) {
    matchers.add(words.slice(0, 3).join(' '))
  }

  // Known aliases
  if (lower.includes('transformational leadership')) {
    matchers.add('transformational leadership')
  }
  if (lower.includes('digital presence')) {
    matchers.add('digital presence')
  }

  return [...matchers].filter((m) => m.length >= 3)
}

function escapeTsString(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

function renderConfig(rows) {
  const generatedAt = new Date().toISOString()
  const entries = rows
    .map((row) => {
      const matchers = row.courseMatchers
        .map((m) => `      '${escapeTsString(m)}'`)
        .join(',\n')
      return `  {
    surveyId: '${escapeTsString(row.surveyId)}',
    surveyTitle: '${escapeTsString(row.surveyTitle)}',
    kind: '${row.kind}',
    courseMatchers: [
${matchers},
    ],
    collectorUrl: '${escapeTsString(row.collectorUrl)}',
  }`
    })
    .join(',\n')

  return `/**
 * Course Pre/Post SurveyMonkey catalog.
 *
 * AUTO-GENERATED by \`npm run sync:course-surveys\` — do not hand-edit the list.
 * Re-run the sync after creating/renaming surveys in SurveyMonkey.
 *
 * Generated: ${generatedAt}
 * Source: SurveyMonkey API (/v3/surveys + collectors)
 */

export type CourseSurveyKind = 'pre' | 'post'

export interface CourseSurveyLink {
  /** SurveyMonkey survey id. */
  surveyId?: string
  /** Human survey title from SurveyMonkey (used for API matching). */
  surveyTitle: string
  kind: CourseSurveyKind
  /** Course title fragment(s) used to match a T4L course. */
  courseMatchers: string[]
  /** SurveyMonkey web collector URL. */
  collectorUrl: string
}

/**
 * Full Pre/Post catalog synced from SurveyMonkey.
 * Only rows with an open (or available) weblink collector URL are included.
 */
export const COURSE_SURVEY_LINKS: CourseSurveyLink[] = [
${entries},
]

/** Legacy fallback used when no course-specific pre survey is configured. */
export const DEFAULT_PRE_COURSE_SURVEY_URL = 'https://www.surveymonkey.com/r/KFM9TPH'

const normalize = (value: string): string =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()

const isExternalRater = (row: CourseSurveyLink): boolean =>
  /external\s*rater/i.test(row.surveyTitle)

export const findCourseSurvey = (
  courseTitle: string | null | undefined,
  kind: CourseSurveyKind,
  options?: { includeExternalRater?: boolean },
): CourseSurveyLink | null => {
  if (!courseTitle?.trim()) return null
  const haystack = normalize(courseTitle)
  const includeExternal = Boolean(options?.includeExternalRater)
  const candidates = COURSE_SURVEY_LINKS.filter((row) => {
    if (row.kind !== kind) return false
    if (!includeExternal && isExternalRater(row)) return false
    return true
  })

  // Prefer the longest matcher hit so "digital presence" beats a generic word.
  let best: CourseSurveyLink | null = null
  let bestLen = 0
  for (const row of candidates) {
    for (const matcher of row.courseMatchers) {
      const needle = normalize(matcher)
      if (!needle) continue
      if (haystack.includes(needle) && needle.length > bestLen) {
        best = row
        bestLen = needle.length
      }
    }
  }
  return best
}

export const listCourseSurveys = (kind?: CourseSurveyKind): CourseSurveyLink[] =>
  kind ? COURSE_SURVEY_LINKS.filter((row) => row.kind === kind) : [...COURSE_SURVEY_LINKS]

export const resolvePreCourseSurveyUrl = (courseTitle?: string | null): string =>
  findCourseSurvey(courseTitle, 'pre')?.collectorUrl ?? DEFAULT_PRE_COURSE_SURVEY_URL

export const resolvePostCourseSurveyUrl = (courseTitle?: string | null): string | null =>
  findCourseSurvey(courseTitle, 'post')?.collectorUrl ?? null
`
}

async function listAllSurveys(token) {
  const out = []
  for (let page = 1; page <= 20; page += 1) {
    const data = await smFetch(token, `/surveys?per_page=100&page=${page}`)
    const batch = data.data || []
    out.push(...batch)
    if (batch.length < 100) break
  }
  return out
}

async function resolveCollectorUrl(token, surveyId) {
  const list = await smFetch(token, `/surveys/${surveyId}/collectors?per_page=50`)
  const collectors = list.data || []
  const preferred =
    collectors.find(
      (c) =>
        String(c.type || '')
          .toLowerCase()
          .includes('weblink') &&
        String(c.status || '')
          .toLowerCase() === 'open',
    ) ||
    collectors.find((c) =>
      String(c.type || '')
        .toLowerCase()
        .includes('weblink'),
    ) ||
    collectors[0]

  if (!preferred?.id) return null
  const detail = await smFetch(token, `/collectors/${preferred.id}`)
  return detail.url || preferred.url || null
}

async function main() {
  const token = loadEnvToken()
  if (!token) {
    console.error(`
Missing SURVEYMONKEY_ACCESS_TOKEN.

Create a local .env (gitignored) with:
  SURVEYMONKEY_ACCESS_TOKEN=your_real_token_here

Copy it from: https://developer.surveymonkey.com/apps/ → T4lAPI → SETTINGS
`)
    process.exit(1)
  }

  console.log('Fetching surveys from SurveyMonkey…')
  const surveys = await listAllSurveys(token)
  console.log(`Found ${surveys.length} survey(s). Resolving Pre/Post collectors…`)

  const rows = []
  const skipped = []

  for (const survey of surveys) {
    const title = survey.title || survey.nickname || survey.id
    const kind = inferKind(title)
    if (kind === 'other') {
      skipped.push({ title, reason: 'not_pre_or_post' })
      continue
    }

    let collectorUrl = null
    try {
      collectorUrl = await resolveCollectorUrl(token, survey.id)
    } catch (err) {
      skipped.push({
        title,
        reason: `collector_error: ${err instanceof Error ? err.message : String(err)}`,
      })
      continue
    }

    if (!collectorUrl) {
      skipped.push({ title, reason: 'no_weblink_collector_url' })
      continue
    }

    rows.push({
      surveyId: String(survey.id),
      surveyTitle: title,
      kind,
      courseMatchers: deriveCourseMatchers(title),
      collectorUrl,
    })
  }

  rows.sort((a, b) => {
    if (a.kind !== b.kind) return a.kind === 'pre' ? -1 : 1
    return a.surveyTitle.localeCompare(b.surveyTitle)
  })

  writeFileSync(OUT_FILE, renderConfig(rows), 'utf8')

  console.log(`\nWrote ${rows.length} Pre/Post survey(s) → src/config/courseSurveys.ts`)
  for (const row of rows) {
    console.log(`  [${row.kind}] ${row.surveyTitle}`)
    console.log(`         ${row.collectorUrl}`)
  }

  if (skipped.length) {
    console.log(`\nSkipped ${skipped.length} survey(s):`)
    for (const s of skipped) {
      console.log(`  - ${s.title} (${s.reason})`)
    }
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
})
